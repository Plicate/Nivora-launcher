fn table_lookup(stem: &str) -> Option<(u16, u16)> {
    for (entry, top, side) in TEXTURE_TABLE {
        if *entry == stem {
            return Some((*top, *side));
        }
    }
    None
}

/// сводит варианты блоков (ступени, плиты, стены, панели, ковры и т.п.)
/// к базовой текстуре материала
fn texture_variants(stem: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::with_capacity(8);
    let push = |value: String, out: &mut Vec<String>| {
        if !value.is_empty() && !out.contains(&value) {
            out.push(value);
        }
    };
    if let Some(head) = stem.strip_suffix("_stained_glass_pane") {
        push(format!("{head}_stained_glass"), &mut out);
    }
    if let Some(_head) = stem.strip_suffix("_glass_pane") {
        push("glass".to_owned(), &mut out);
    }
    for suffix in ["_carpet", "_bed", "_banner", "_wall_banner"] {
        if let Some(head) = stem.strip_suffix(suffix) {
            push(format!("{head}_wool"), &mut out);
        }
    }
    for suffix in [
        "_stairs",
        "_slab",
        "_wall",
        "_fence",
        "_fence_gate",
        "_button",
        "_pressure_plate",
        "_trapdoor",
        "_door",
        "_sign",
        "_wall_sign",
        "_hanging_sign",
        "_carpet",
        "_bed",
        "_banner",
        "_pane",
    ] {
        if let Some(head) = stem.strip_suffix(suffix) {
            push(head.to_owned(), &mut out);
            push(format!("{head}s"), &mut out);
            push(format!("{head}_planks"), &mut out);
            push(format!("{head}_block"), &mut out);
        }
    }
    out
}

pub fn texture_cells(name: &str) -> (u16, u16) {
    let raw = name.trim_start_matches("minecraft:");
    let stem = raw.split('[').next().unwrap_or(raw);
    if let Some(cells) = table_lookup(stem) {
        return cells;
    }
    if let Some(stripped) = stem.strip_suffix("_top") {
        if let Some(cells) = table_lookup(stripped) {
            return cells;
        }
    }
    for candidate in texture_variants(stem) {
        if let Some(cells) = table_lookup(&candidate) {
            return cells;
        }
    }
    table_lookup("stone").unwrap_or((FALLBACK_CELL, FALLBACK_CELL))
}
